// 视频：申请 HTTPS 证书（ACME DNS-01 → 自动续期 → 监听启用 HTTPS）
import { record } from '../video.mjs'

await record('https-certificate', {
  title: '申请 HTTPS 证书',
  summary: '用 ACME 免费申请证书，到期前自动续期',
  steps: ['打开「SSL 证书」点「添加证书」', '填域名，选 DNS 验证与服务商', '保存后自动签发', '在监听里启用 HTTPS']
}, async (v) => {
  const { page } = v
  await v.go('ssl', 1200)
  await v.step('证书列表')
  await v.cap('「Web → SSL 证书」列出全部证书：域名、颁发机构与剩余天数，到期前自动续期')
  await v.sleep(4000)
  await v.step('第 1 步')
  await v.cap('点「添加证书」，来源选「ACME 自动申请」')
  await v.click(page.getByRole('button', { name: '添加证书', exact: true }))
  const d = page.locator('.el-dialog:visible').last()
  const item = (label) => d.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: label }) }).first()
  await v.step('第 2 步')
  await v.cap('填写域名，可以写多个，泛域名写成 *.example.com')
  const dom = item('域名').locator('textarea').first()
  await v.type(dom, 'example.com')
  await page.keyboard.press('Enter')
  await dom.pressSequentially('*.example.com', { delay: 70 })
  await v.sleep(800)
  await v.cap('DNS-01 支持泛域名，不需要开放 80 端口；HTTP-01 适合 80 端口能从公网访问的情况')
  await v.point(d.getByText('DNS-01（支持通配符）'))
  await v.sleep(2000)
  await v.cap('选择域名所在的 DNS 服务商，填入 API 凭据（「获取凭据」链接说明在哪里创建）')
  await v.click(item('DNS 服务商').locator('.el-select').first())
  const opt = page.locator('.el-select-dropdown__item:visible', { hasText: 'Cloudflare' }).first()
  await v.click(opt)
  await v.sleep(800)
  const secret = d.locator('.el-form-item').filter({ hasText: /Token|Secret/ }).locator('input:visible').last()
  await v.type(secret, 'cf-api-token-example', 40)
  await v.step('第 3 步')
  await v.cap('点「保存」后立即开始签发，签发与续期的进度写在运行日志里')
  await v.click(d.getByRole('button', { name: '保存', exact: true }))
  await v.sleep(2500)
  await v.cap('「续签设置」里可以调整提前多少天续期；续期失败会按通知设置发出告警')
  await v.point(page.getByRole('button', { name: '续签设置', exact: true }))
  await v.sleep(2500)
  await v.step('第 4 步')
  await v.go('web', 1200)
  await v.cap('在「Web 服务」里编辑监听，打开 HTTPS：站点按域名自动匹配已有证书')
  await v.click(page.getByRole('button', { name: '编辑监听', exact: true }).first())
  await v.sleep(1200)
  const ld = page.locator('.el-dialog:visible').last()
  await v.point(ld.locator('.el-form-item').filter({ hasText: 'HTTPS' }).first().locator('.el-switch').first())
  await v.sleep(1500)
  await v.cap('「HTTP 端口」设为 80 并选择跳转，访客输入 http 地址会自动跳到 https')
  await v.point(ld.locator('.el-form-item').filter({ hasText: 'HTTP 端口' }).first())
  await v.sleep(3500)
  await page.keyboard.press('Escape')
  await v.sleep(800)
})
